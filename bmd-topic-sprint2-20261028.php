/** Preserve featured image, slug, categories, byline and date; backup source. */
add_action('init',function() {
    $key='bmd_sprint2_editorial_oct28_v1';
    if (get_option($key,false)==='applied') { return; }
    $changes=array();
    foreach(bmd_oct28_sprint2_posts() as $slug=>$cfg) {
        $p=get_page_by_path($slug,OBJECT,'post');
        if (!$p || (int)$p->ID!==(int)$cfg['id'] || $p->post_status!=='publish') {
            $changes[$slug]='not-found-or-mismatch';continue;
        }
        $original=(string)$p->post_content;
        if (metadata_exists('post',$p->ID,'_bmd_sprint2_backup_oct28')) {
            $changes[$slug]='already-backed-up';continue;
        }
        if(strlen($original)<1200 || strlen($original)>40000 ||
            stripos(wp_strip_all_tags($original),$cfg['needle'])===false) {
            $changes[$slug]='guard-mismatch';continue;
        }
        if(!add_post_meta($p->ID,'_bmd_sprint2_backup_oct28',$original,true)){
            $changes[$slug]='backup-failed';continue;
        }
        $res=wp_update_post(array('ID'=>$p->ID,'post_title'=>$cfg['title'],'post_content'=>$cfg['content']),true);
        if(is_wp_error($res)||!$res){
            delete_post_meta($p->ID,'_bmd_sprint2_backup_oct28');
            $changes[$slug]='update-failed';continue;
        }
        update_post_meta($p->ID,'rank_math_title',$cfg['seo_title']);
        update_post_meta($p->ID,'rank_math_description',$cfg['description']);
        clean_post_cache($p->ID);
        $changes[$slug]='applied';
    }
    update_option($key,count(array_filter($changes,function($x){return $x!=='applied'&&$x!=='already-backed-up';}))?wp_json_encode($changes):'applied',false);
},31);

